const assert = require('node:assert/strict');
require('../js/class-session-ledger.js');
const ledger = globalThis.ClassSessionLedger;
const original = {pacoteContratado:16, classCount:6, valorPacote:700, lastClassRegisteredAt:'2026-09-01T12:00:00Z', classRegistrationHistory:['2026-09-01T12:00:00Z'], progress:{a1:{lesson_1:true}}};
const input = {id:'meeting-1', packageId:'legacy', durationMinutes:45, startsAt:'2026-09-10T12:00:00Z', note:'Leitura e conversa.'};
let data = {...original, ...ledger.record(original,input,'teacher','2026-09-11T12:00:00Z')};
assert.equal(data.classCount,6.75);
assert.equal(original.classCount,6);
assert.equal(original.classSessions,undefined);
assert.equal(data.classSessions.length,1);
data = {...data,...ledger.record(data,{...input,durationMinutes:30,expectedUpdatedAt:data.classSessions[0].updatedAt},'teacher','2026-09-11T13:00:00Z')};
assert.equal(data.classCount,6.5);
assert.equal(data.classSessions[0].createdAt,'2026-09-11T12:00:00Z');
assert.equal(ledger.record(data,{...input,durationMinutes:30},'teacher').classCount,6.5,'Retry must not double count');
assert.throws(()=>ledger.record(data,{...input,expectedUpdatedAt:'stale'},'teacher'),/alterado/);
assert.throws(()=>ledger.record(data,{...input,packageId:'different'},'teacher'),/pacote mudou/);
assert.throws(()=>ledger.record({...data,pacoteContratado:0},input,'teacher'),/Inicie/);
for(const durationMinutes of [-15,0,22,241,Infinity]) assert.throws(()=>ledger.record(data,{...input,durationMinutes},'teacher'));
assert.throws(()=>ledger.record(data,{...input,note:'x'.repeat(501)},'teacher'));
assert.throws(()=>ledger.record(data,{...input,startsAt:'invalid'},'teacher'));
const moved = ledger.record(data,{...input,startsAt:'2026-08-20T12:00:00Z'},'teacher');
assert.equal(moved.lastClassRegisteredAt,'2026-09-01T12:00:00.000Z','Legacy latest date must survive date corrections');
const patch = ledger.startPackage(data,{id:'new-package',hours:8,value:400,startDate:'2026-09-11'});
assert.equal(patch.classCount,0);
assert.equal(patch.packageHistory[0].usedMinutes,390);
assert.deepEqual(patch.packageHistory[0].legacyDates,original.classRegistrationHistory);
assert.equal(patch.classSessions,undefined,'Archive must not overwrite encounters');
assert.equal(patch.progress,undefined,'Package changes must not overwrite lesson progress');
data = {...data,...patch};
assert.throws(()=>ledger.record(data,{...input,packageId:'new-package'},'teacher'),/pacote anterior/);
data = {...data,...ledger.record(data,{...input,id:'meeting-2',packageId:'new-package',durationMinutes:90},'teacher')};
assert.equal(data.classCount,1.5);
assert.equal(data.classSessions.length,2);
assert.equal(data.packageHistory.length,1);
for(const value of [-1,NaN,Infinity])assert.throws(()=>ledger.startPackage(data,{id:'x',hours:8,value,startDate:'2026-09-11'}));
console.log('PASS: duration accounting, edits, retries, stale data, validation, legacy dates and package archives.');
