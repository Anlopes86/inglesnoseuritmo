    function toPortuguese(text) {
        return translations[String(text || '').trim()] || '';
    }

    function enhance(root) {
        const scope = root || document;
        const nodes = [];
        if (scope instanceof Element && scope.matches('[data-v3-translate]')) nodes.push(scope);
        scope.querySelectorAll?.('[data-v3-translate]').forEach(node => nodes.push(node));
        nodes.forEach(node => {
            if (node.dataset.v3TranslationReady) return;
            const source = node.dataset.v3Translate || '';
            const translation = node.dataset.v3Translation || toPortuguese(source);
            if (!translation) {
                node.dataset.v3TranslationMissing = 'true';
                return;
            }
            node.textContent = translation;
            node.dataset.v3TranslationReady = 'true';
            node.removeAttribute('data-v3-translation-missing');
        });
    }

    function init() {
        enhance(document);
        const observer = new MutationObserver(mutations => {
            mutations.forEach(mutation => mutation.addedNodes.forEach(node => {
                if (node instanceof Element) enhance(node);
            }));
        });
        observer.observe(document.body, { childList: true, subtree: true });
    }

    window.V3Translations = { translations, toPortuguese, enhance };
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
